def 읽기(경로):
    d = json.load(io.open(경로, encoding='utf-8'))
    return d['line_of_sight'], d['resolution']['map_size']['x'], d['resolution']['map_size']['y']


def 옮긴_윤곽(윤곽):
    """위여백만큼 아래로 · 윤곽_내림 만큼 더 내린 사본."""
    결과 = []
    for i, p in enumerate(윤곽):
        dy = 위여백 + 윤곽_내림.get(i, 0.0)
        결과.append([{'x': q['x'], 'y': q['y'] + dy} for q in p])
    return 결과


def 칸사각(r):
    return int(r[1] * N), int(r[3] * N), int(r[0] * N), int(r[2] * N)


def 칠하기(m, 사각들, 값):
    for r in 사각들:
        x0, y0, x1, y1 = r
        y0, y1 = y0 + 위여백, y1 + 위여백
        m[max(int(y0 * N), 0):int(y1 * N), max(int(x0 * N), 0):int(x1 * N)] = 값


def 월드(고리):
    return [[x / N * 칸 + OX, y / N * 칸 + OY] for x, y in 고리]


def 사각_월드(p):
    xs = [q['x'] for q in p]
    ys = [q['y'] for q in p]
    # 도면 꼭짓점에 89.0003 같은 잔떨림이 있다 → 16px(0.5 칸) 격자에 붙인다(검산 격자와 같다).
    붙임 = lambda v: round(v / 16.0) * 16.0
    return [붙임(min(xs) * 칸 + OX), 붙임(min(ys) * 칸 + OY), 붙임(max(xs) * 칸 + OX), 붙임(max(ys) * 칸 + OY)]


def 조각들_월드(m, 접두):
    결과 = []
    lab, n = 덩어리들(m)
    for c in range(1, n + 1):
        덩 = (lab == c)
        ys, xs = np.where(덩)
        왼, 오 = xs.min() / N, (xs.max() + 1) / N
        경계 = [왼]
        if (오 - 왼) > 60:
            for x in 자르는_x:
                k = int(x * N)
                if 왼 < x < 오 and not np.array_equal(덩[:, k - 1], 덩[:, k]):
                    경계.append(x)
        경계.append(오)
        for k, (a, b) in enumerate(zip(경계, 경계[1:])):
            잘린 = 덩.copy()
            if len(경계) > 2:
                잘린[:, :int(a * N)] = False
                잘린[:, int(b * N):] = False
            하위, hn = 덩어리들(잘린)
            for s in range(1, hn + 1):
                고리 = 외곽선(하위 == s)
                if len(고리) > 1:
                    print('  ⚠ %s%02d 에 구멍 %d 개 — 바깥만 쓴다' % (접두, c, len(고리) - 1))
                이름 = '%s%02d' % (접두, c) + ('' if len(경계) == 2 else '_%d' % k) + ('' if hn == 1 else chr(ord('a') + s - 1))
                # 덩어리 안의 아무 칸 → 원래 도면 윤곽 번호를 알 수 있게 대표 칸(도면 좌표)을 남긴다
                yy, xx = np.where(하위 == s)
                결과.append({'이름': 이름, '점': 월드(직선_합치기(고리[0])),
                           '대표': [float(xx[0]) / N, float(yy[0]) / N - 위여백]})
    return 결과


