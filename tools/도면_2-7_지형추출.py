def 읽기(경로):
    d = json.load(io.open(경로, encoding='utf-8'))
    return d['line_of_sight'], d['resolution']['map_size']['x'], d['resolution']['map_size']['y']


def 칸사각(r):
    return int(r[1] * N), int(r[3] * N), int(r[0] * N), int(r[2] * N)


def 칠하기(m, 사각들, 값):
    for r in 사각들:
        y0, y1, x0, x1 = 칸사각(r)
        m[y0:y1, x0:x1] = 값


def 조각들_월드(m, 접두, 이름표=None):
    """덩어리마다 바깥 외곽선을 딴다. 60 칸보다 넓은 덩어리는 모양이 바뀌는 `자르는_x` 에서만 세로로 자른다."""
    결과 = []
    lab, n = 덩어리들(m)
    for c in range(1, n + 1):
        덩 = (lab == c)
        ys, xs = np.where(덩)
        왼, 오 = xs.min() / N, (xs.max() + 1) / N
        경계 = [왼]
        if (오 - 왼) > 60:
            for x in 자르는_x:
                k = int(x * N)
                if 왼 < x < 오 and not np.array_equal(덩[:, k - 1], 덩[:, k]):
                    경계.append(x)
        경계.append(오)
        for k, (a, b) in enumerate(zip(경계, 경계[1:])):
            잘린 = 덩.copy()
            if len(경계) > 2:
                잘린[:, :int(a * N)] = False
                잘린[:, int(b * N):] = False
            하위, hn = 덩어리들(잘린)
            for s in range(1, hn + 1):
                고리 = 외곽선(하위 == s)
                if len(고리) > 1:
                    print('  ⚠ %s%02d 에 구멍 %d 개 — 바깥만 쓴다' % (접두, c, len(고리) - 1))
                이름 = '%s%02d' % (접두, c) + ('' if len(경계) == 2 else '_%d' % k) + ('' if hn == 1 else chr(ord('a') + s - 1))
                결과.append({'이름': 이름, '점': 월드(직선_합치기(고리[0]))})
    return 결과


