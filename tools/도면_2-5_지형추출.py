def 읽기(경로):
    d = json.load(io.open(경로, encoding='utf-8'))
    return d['line_of_sight'], d['resolution']['map_size']['x'], d['resolution']['map_size']['y']


def 칸사각(r):
    return int(r[1] * N), int(r[3] * N), int(r[0] * N), int(r[2] * N)


def 고리들_월드(m, 접두):
    """덩어리마다 바깥 외곽선만 딴다. 구멍(안쪽 고리)이 있으면 알린다 — SS2D 는 구멍을 못 그린다."""
    결과 = []
    lab, n = 덩어리들(m)
    for c in range(1, n + 1):
        고리 = 외곽선(lab == c)
        if len(고리) > 1:
            print('  ⚠ %s%02d 에 구멍 %d 개 — 바깥만 쓴다' % (접두, c, len(고리) - 1))
        결과.append({'이름': '%s%02d' % (접두, c), '점': 월드(직선_합치기(고리[0]))})
    return 결과


def main():
    경로 = sys.argv[1] if len(sys.argv) > 1 else 기본_도면
    윤곽, W, H = 읽기(경로)
    print('도면 %s · %d×%d 칸 · 윤곽 %d' % (os.path.basename(경로), W, H, len(윤곽)))

    흰 = 래스터(윤곽, list(흰지형), W, H)
    m = 래스터(윤곽, 바위, W, H) & ~흰
    for r in 통로 + 손_파냄:
        y0, y1, x0, x1 = 칸사각(r)
        m[y0:y1, x0:x1] = False
        흰[y0:y1, x0:x1] = False

    하늘 = np.zeros(m.shape, bool)
    for r in 손_채움:
        y0, y1, x0, x1 = 칸사각(r)
        하늘[y0:y1, x0:x1] = True
    하늘 &= ~(m | 흰)

    지형 = 고리들_월드(m, '덩')
    흰조각 = 고리들_월드(흰, '흰')
    채움 = 고리들_월드(하늘, '채움')

    빈 = ~(m | 흰 | 하늘)
    빈공간 = [[round(x0 / N * 칸 + OX, 1), round(y0 / N * 칸 + OY, 1),
               round((x1 - x0) / N * 칸, 1), round((y1 - y0) / N * 칸, 1)]
              for x0, y0, x1, y1 in 사각_덮기(빈)]

    결과 = {
        '칸': 칸, '오프셋': [OX, OY],
        '프레임': [OX, OY, W * 칸, H * 칸],
        '지형': 지형,
        '흰지형': 흰조각,
        '채움': 채움,
        '빈공간': 빈공간,
        '격자': [{'이름': v[0], '색': v[1], '사각': 사각_월드(윤곽[k])} for k, v in sorted(격자.items())],
        '계단': [{'번호': v, '사각': 사각_월드(윤곽[k])} for k, v in sorted(계단.items(), key=lambda a: a[1])],
        '유령': {v: 사각_월드(윤곽[k]) for k, v in 유령.items()},
        '가시': {v: 사각_월드(윤곽[k]) for k, v in 가시.items()},
        '버튼': {v: 사각_월드(윤곽[k]) for k, v in 버튼.items()},
        '양동이': {v: 사각_월드(윤곽[k]) for k, v in 양동이.items()},
    }
    나갈곳 = os.path.join(여기, '도면_2-5_지형.json')
    with io.open(나갈곳, 'w', encoding='utf-8') as f:
        json.dump(결과, f, ensure_ascii=False, indent=1)
    print('바위 %d · 흰 %d · 채움 %d · 빈공간 사각 %d → %s' % (len(지형), len(흰조각), len(채움), len(빈공간), 나갈곳))
    for s in 지형 + 흰조각 + 채움:
        xs = [p[0] for p in s['점']]
        ys = [p[1] for p in s['점']]
        print('  %-8s 점 %3d  x %6.0f~%-6.0f y %6.0f~%-6.0f  (칸 x %5.1f~%-5.1f y %5.1f~%-5.1f)' %
              (s['이름'], len(s['점']), min(xs), max(xs), min(ys), max(ys),
               (min(xs) - OX) / 칸, (max(xs) - OX) / 칸, (min(ys) - OY) / 칸, (max(ys) - OY) / 칸))


if __name__ == '__main__':
    main()
