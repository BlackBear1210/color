def 읽기(경로):
    d = json.load(io.open(경로, encoding='utf-8'))
    return d['line_of_sight'], d['resolution']['map_size']['x'], d['resolution']['map_size']['y']


def 칸사각(r):
    return int(r[1] * N), int(r[3] * N), int(r[0] * N), int(r[2] * N)


def 조각들_월드(m, 접두):
    """덩어리마다 바깥 외곽선을 딴다. 60 칸보다 넓은 덩어리는 `자르는_x` 에서 세로로 자른다(2-4 와 같다)."""
    결과 = []
    경계 = [0.0] + 자르는_x + [float(프레임_W)]
    lab, n = 덩어리들(m)
    for c in range(1, n + 1):
        덩 = (lab == c)
        ys, xs = np.where(덩)
        왼, 오 = xs.min() / N, (xs.max() + 1) / N
        구간 = [(a, b) for a, b in zip(경계, 경계[1:]) if b > 왼 and a < 오] if (오 - 왼) > 60 else [(왼, 오)]
        for k, (a, b) in enumerate(구간):
            잘린 = 덩.copy()
            if len(구간) > 1:
                잘린[:, :int(a * N)] = False
                잘린[:, int(b * N):] = False
            하위, hn = 덩어리들(잘린)
            for s in range(1, hn + 1):
                고리 = 외곽선(하위 == s)
                if len(고리) > 1:
                    print('  ⚠ %s%02d 에 구멍 %d 개 — 바깥만 쓴다' % (접두, c, len(고리) - 1))
                이름 = '%s%02d' % (접두, c) + ('' if len(구간) == 1 else '_%d' % k) + ('' if hn == 1 else chr(ord('a') + s - 1))
                결과.append({'이름': 이름, '점': 월드(직선_합치기(고리[0]))})
    return 결과


def main():
    경로 = sys.argv[1] if len(sys.argv) > 1 else 기본_도면
    윤곽, W, H = 읽기(경로)
    print('도면 %s · %d×%d 칸 · 윤곽 %d · 프레임 %d×%d' % (os.path.basename(경로), W, H, len(윤곽), 프레임_W, H))
    W = 프레임_W

    흰 = 래스터(윤곽, list(흰지형), W, H)
    m = 래스터(윤곽, 바위, W, H) & ~흰
    하늘 = np.zeros(m.shape, bool)
    for r in 손_채움:
        y0, y1, x0, x1 = 칸사각(r)
        하늘[y0:y1, x0:x1] = True
    for r in 통로 + 손_파냄:
        y0, y1, x0, x1 = 칸사각(r)
        m[y0:y1, x0:x1] = False
        흰[y0:y1, x0:x1] = False
        하늘[y0:y1, x0:x1] = False
    하늘 &= ~(m | 흰)

    지형 = 조각들_월드(m, '덩')
    흰조각 = 조각들_월드(흰, '흰')
    채움 = 조각들_월드(하늘, '채움')

    빈 = ~(m | 흰 | 하늘)
    빈공간 = [[round(x0 / N * 칸 + OX, 1), round(y0 / N * 칸 + OY, 1),
               round((x1 - x0) / N * 칸, 1), round((y1 - y0) / N * 칸, 1)]
              for x0, y0, x1, y1 in 사각_덮기(빈)]

    결과 = {
        '칸': 칸, '오프셋': [OX, OY],
        '프레임': [OX, OY, W * 칸, H * 칸],
        '지형': 지형,
        '흰지형': 흰조각,
        '채움': 채움,
        '빈공간': 빈공간,
        '호퍼': {v: 사각_월드(윤곽[k]) for k, v in 호퍼.items()},
        '격자': [{'이름': v[0], '색': v[1], '사각': 사각_월드(윤곽[k])} for k, v in sorted(격자.items(), key=lambda a: a[1][0])],
        '유령': {v: 사각_월드(윤곽[k]) for k, v in 유령.items()},
        '버튼': {v: 사각_월드(윤곽[k]) for k, v in 버튼.items()},
        '양동이': {v: 사각_월드(윤곽[k]) for k, v in 양동이.items()},
        '움직이는_발판': {v: 사각_월드(윤곽[k]) for k, v in 움직이는_발판.items()},
        '톱': {v: 사각_월드(윤곽[k]) for k, v in 톱.items()},
    }
    나갈곳 = os.path.join(여기, '도면_2-6_지형.json')
    with io.open(나갈곳, 'w', encoding='utf-8') as f:
        json.dump(결과, f, ensure_ascii=False, indent=1)
    print('바위 %d · 흰 %d · 채움 %d · 빈공간 사각 %d → %s' % (len(지형), len(흰조각), len(채움), len(빈공간), 나갈곳))
    for s in 지형 + 흰조각 + 채움:
        xs = [p[0] for p in s['점']]
        ys = [p[1] for p in s['점']]
        print('  %-10s 점 %3d  x %6.0f~%-6.0f y %6.0f~%-6.0f  (칸 x %5.1f~%-5.1f y %5.1f~%-5.1f)' %
              (s['이름'], len(s['점']), min(xs), max(xs), min(ys), max(ys),
               (min(xs) - OX) / 칸, (max(xs) - OX) / 칸, (min(ys) - OY) / 칸, (max(ys) - OY) / 칸))


if __name__ == '__main__':
    main()
