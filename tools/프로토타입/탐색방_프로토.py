# 검증 — **행동을 하나씩 빼 보는 대조 검사**가 핵심이다
# ----------------------------------------------------------------------------
# ▣ 왜 관문 개수를 세면 안 되나 (작업지시 §5)
#   관문을 놓았다는 것과 그 관문이 **강제된다**는 것은 전혀 다른 말이다.
#   발판 하나가 옆에 더 놓이면 구덩이는 그냥 돌아가는 길이 된다.
#   → 점프 / 칠하기 / 색전환을 **빼고** 같은 검사를 다시 돌려서,
#     빠졌을 때 진짜로 막히는지를 본다. 막히지 않으면 그 관문은 장식이다.
#
# ▣ 판정 잣대는 규격.gd 하나뿐
#   한 번에 오르는 높이 1 칸(96 <= 설계_최대상승 112), 건너는 틈 2 칸(192 <= 설계_최대틈 224),
#   그리고 **실제 포물선**(점프로_닿나)까지 같이 본다. 예산 두 개를 동시에 쓰면
#   "이론상 가능" 이 되는 자리가 생기기 때문이다.
# ============================================================================
이동_걷기, 이동_점프, 이동_상승, 이동_낙하 = "걷기", "점프", "상승", "낙하"


class 세계:
    """능력(점프/칠하기/색전환)에 따라 달라지는 지형 해석 + 이동 규칙."""

    def __init__(self, 방, 점프=True, 칠하기=True, 색전환=True):
        self.방 = 방
        self.점프 = 점프
        self.칠하기 = 칠하기
        self.색전환 = 색전환
        self.발판칸 = {}
        for p in 방.플랫폼들:
            for x in range(p["x0"], p["x1"] + 1):
                self.발판칸[(x, p["몸행"])] = p
        self.가시 = set(방.가시칸)
        self._설캐시 = {}

    # -- 지형 해석 ----------------------------------------------------------
    def 고체(self, x: int, y: int) -> bool:
        if self.방.읽기(x, y) == 암반:
            return True
        p = self.발판칸.get((x, y))
        if p is None:
            return False
        if p["종류"] == "유령":
            return self.칠하기            # 안 칠하면 **없는 것과 같다**
        return True                        # 발판 · 색슬래브는 언제나 단단하다

    def 치명(self, x: int, y: int) -> bool:
        """닿으면 죽는 칸(가시). 색슬래브는 '밟을 수 없다' 로 따로 본다."""
        return (x, y) in self.가시

    def 밟을_수_있나(self, x: int, y: int) -> bool:
        """그 칸을 **지지면으로** 쓸 수 있나. 색슬래브는 색을 맞출 수단이 있어야 한다."""
        p = self.발판칸.get((x, y))
        if p is not None and p["종류"] == "색슬래브":
            return self.색전환 or self.칠하기
        return self.고체(x, y)

    def 설_수_있나(self, x: int, y: int) -> bool:
        키 = (x, y)
        v = self._설캐시.get(키)
        if v is not None:
            return v
        r = (not self.고체(x, y) and not self.치명(x, y)
             and not self.고체(x, y - 1) and not self.치명(x, y - 1)
             and self.밟을_수_있나(x, y + 1))
        self._설캐시[키] = r
        return r

    def _통과(self, x: int, y: int) -> bool:
        return not self.고체(x, y) and not self.치명(x, y)

    def _상자_빈가(self, x0: int, y0: int, x1: int, y1: int) -> bool:
        for y in range(min(y0, y1), max(y0, y1) + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                if not self._통과(x, y):
                    return False
        return True

    # -- 이동 규칙 ----------------------------------------------------------
    def 이웃(self, p):
        x, y = p
        out = []
        for dx in range(-3, 4):
            for dy in range(-1, 16):
                if dx == 0 and dy == 0:
                    continue
                q = (x + dx, y + dy)
                if not self.설_수_있나(q[0], q[1]):
                    continue
                가로틈 = (abs(dx) - 1) * 96.0 if abs(dx) >= 1 else 0.0
                if dy < 0:                                    # 올라간다
                    if not self.점프 or dy != -1:
                        continue
                    if not 점프로_닿나(max(가로틈, 0.0), 96.0):
                        continue
                    # ★빈 공간을 요구하는 범위는 **올라갈 줄과 그 머리 줄**뿐이다.
                    #   출발 칸의 줄(y)까지 비어 있으라고 하면, 목표 선반의 **옆면 바위**가
                    #   걸려서 "선반 가장자리로 올라서기" 가 전부 불가로 판정된다(실측 도달 17 칸).
                    if not self._상자_빈가(x, q[1] - 1, q[0], q[1]):
                        continue
                    out.append((q, 5, 이동_상승))
                elif dy == 0:                                 # 같은 높이
                    if abs(dx) == 1:
                        if not self._상자_빈가(x, y - 1, q[0], q[1]):
                            continue
                        out.append((q, 1, 이동_걷기))
                    else:
                        if not self.점프:
                            continue
                        if 가로틈 > 설계_최대틈:
                            continue
                        if not self._상자_빈가(x, y - 1, q[0], q[1]):
                            continue
                        out.append((q, 4, 이동_점프))
                else:                                         # 떨어진다
                    if abs(dx) >= 2 and not self.점프:
                        continue
                    if dy * 96.0 > 치명_낙하:
                        continue
                    # ★네모 전체를 비우라고 하면 **지금 밟고 선 바닥**까지 비어야 해서
                    #   한 칸 내려가는 이동이 전부 막힌다(실측: 계단탑 밑 통로에 못 들어갔다).
                    #   실제 경로는 ㄱ 자다 — 머리 높이로 옆으로 나간 뒤 그 자리에서 떨어진다.
                    if not self._상자_빈가(x, y - 1, q[0], y - 1):
                        continue
                    if not self._상자_빈가(q[0], y - 1, q[0], q[1]):
                        continue
                    out.append((q, 2 + dy, 이동_낙하))
        return out


def 이동비용(세: 세계, 시작) -> dict:
    """다익스트라. 돌려주는 것 = {칸: 비용}. 비용은 '걷기 1' 기준의 상대값이다."""
    import heapq
    s = tuple(시작)
    if not 세.설_수_있나(s[0], s[1]):
        # 스폰 직후 낙하 — 바로 아래에서 설 수 있는 칸을 찾는다
        for d in range(1, 20):
            if 세.설_수_있나(s[0], s[1] + d):
                s = (s[0], s[1] + d)
                break
        else:
            return {}
    거리 = {s: 0}
    큐 = [(0, s)]
    while 큐:
        d, p = heapq.heappop(큐)
        if d > 거리.get(p, 1 << 30):
            continue
        for q, c, _종류 in 세.이웃(p):
            nd = d + c
            if nd < 거리.get(q, 1 << 30):
                거리[q] = nd
                heapq.heappush(큐, (nd, q))
    return 거리


def 되돌아올_수_있나(세: 세계, 도달: dict, 목표) -> set:
    """도달한 칸들 중 **목표로 되돌아올 수 있는** 칸의 집합(역방향 BFS)."""
    역 = {}
    for p in 도달:
        for q, _c, _t in 세.이웃(p):
            if q in 도달:
                역.setdefault(q, []).append(p)
    본 = set()
    줄 = [tuple(목표)]
    if tuple(목표) not in 도달:
        return 본
    본.add(tuple(목표))
    while 줄:
        p = 줄.pop()
        for q in 역.get(p, ()):
            if q not in 본:
                본.add(q)
                줄.append(q)
    return 본


