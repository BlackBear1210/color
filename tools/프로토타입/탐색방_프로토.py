        self.W = 설정값.폭칸
        self.H = 설정값.높이칸
        self.칸 = bytearray([암반]) * (self.W * self.H)
        self.벽 = 설정값.외곽두께 + 설정값.여백
        self.L, self.R = self.벽, self.W - self.벽
