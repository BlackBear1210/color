# ----------------------------------------------------------------------------
# ▣ 스트림을 나누는 이유 (작업지시 §6)
#   "배경 변형 하나를 추가했다고 출구가 바뀌면 안 된다."
#   → 지형·출구·관문·장식이 **각자의 난수**를 쓴다. 한 쪽을 더 뽑아도 다른 쪽은 그대로다.
