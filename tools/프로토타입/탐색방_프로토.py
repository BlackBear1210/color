M64 = (1 << 64) - 1
스트림 = {"지형": 1, "출구": 2, "관문": 3, "장식": 4}


class 난수:
    def __init__(self, 씨앗: int, 이름: str):
        s = (씨앗 * 0x9E3779B97F4A7C15 + 스트림[이름] * 0xD1B54A32D192ED03) & M64
        self.상태 = s
        self.이름 = 이름
        for _ in range(4):          # 워밍업 — 씨앗 1,2,3 이 비슷해 보이지 않게
            self._다음()

    def _다음(self) -> int:
        self.상태 = (self.상태 + 0x9E3779B97F4A7C15) & M64
        z = self.상태
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M64
        return (z ^ (z >> 31)) & M64

    def 정수(self, a: int, b: int) -> int:
        """a 이상 b 이하."""
        if b <= a:
            return a
        폭 = b - a + 1
        return a + ((self._다음() >> 1) & 0x3FFFFFFFFFFFFFFF) % 폭

    def 확률(self, 퍼센트: int) -> bool:
        return self.정수(0, 99) < 퍼센트

    def 하나(self, 목록: list):
        return 목록[self.정수(0, len(목록) - 1)]


