# 출구 선택 — 생성 때 **한 번** 고르고, 같은 씨앗이면 같은 자리를 저장한다
# ============================================================================
def 출구_고르기(방, 보고: dict) -> dict:
    설정값 = 방.설정
    전능력 = 세계(방)
    입구 = next(s for s in 방.소켓들 if s["역할"] == "입구")
    시작 = 입구["칸"]
    거리 = 이동비용(전능력, 시작)
    보고["도달칸수"] = len(거리)

    무점프 = 세계(방, 점프=False)
    무점프거리 = 이동비용(무점프, 시작)
    돌아옴 = 되돌아올_수_있나(전능력, 거리, 시작)

    후보 = []
    for s in 방.소켓들:
        if s["역할"] == "입구":
            continue
        칸 = tuple(s["칸"])
        기록 = {"id": s["id"], "구역": s["구역"], "높이단": s["높이단"],
                "방향": s["방향"], "칸": list(칸)}
        if 칸 not in 거리:
            기록["제외"] = "도달 불가"
        elif 거리[칸] < 설정값.출구_최소비용:
            기록["제외"] = "입구에서 너무 가깝다(비용 %d)" % 거리[칸]
        elif 칸 in 무점프거리:
            기록["제외"] = "걸어서만 닿는다(점프 없이 도달)"
        elif 칸 not in 돌아옴:
            기록["제외"] = "되돌아올 수 없다(일방 함정)"
        else:
            안전 = 스폰_안전(방, 전능력, 칸)
            if 안전:
                기록["제외"] = 안전
            else:
                기록["제외"] = ""
                기록["비용"] = 거리[칸]
        기록.setdefault("비용", 거리.get(칸, -1))
        후보.append(기록)

    살아있음 = [c for c in 후보 if c["제외"] == ""]
    보고["출구후보"] = 후보
    if not 살아있음:
        보고["출구실패"] = "쓸 수 있는 출구 후보가 없다"
        return {}

    최대 = max(c["비용"] for c in 살아있음)
    문턱 = 최대 * (100 - 설정값.출구_상위비율) / 100.0
    뽑이 = [c for c in 살아있음 if c["비용"] >= 문턱]
    살아있음.sort(key=lambda c: -c["비용"])
    while len(뽑이) < min(설정값.출구_최소후보, len(살아있음)):
        for c in 살아있음:
            if c not in 뽑이:
                뽑이.append(c)
                break
    뽑이.sort(key=lambda c: c["id"])          # 순서를 고정해야 씨앗이 뜻을 갖는다
    고름 = 뽑이[방.출구난수.정수(0, len(뽑이) - 1)]
    보고["출구뽑이"] = [c["id"] for c in 뽑이]
    for s in 방.소켓들:
        if s["id"] == 고름["id"]:
            s["역할"] = "출구"
            return s
    return {}


def 스폰_안전(방, 세: 세계, 칸) -> str:
    """빈 문자열이면 안전. 아니면 그 이유."""
    x, y = 칸
    if not 세.설_수_있나(x, y):
        return "착지 칸에 설 수 없다"
    for dx in range(-2, 3):
        if (x + dx, y) in 세.가시 or (x + dx, y + 1) in 세.가시:
            return "가시가 2 칸 안에 있다"
    for dx in range(-3, 4):
        p = 세.발판칸.get((x + dx, y + 1))
        if p is not None and p["종류"] == "색슬래브":
            return "스폰 자리 지지면이 색슬래브다(반대색 접촉사)"
        if p is not None and p["종류"] == "유령":
            return "스폰 자리 지지면이 유령 발판이다(안 칠하면 떨어진다)"
    if 세.방.읽기(x, y + 1) != 암반 and 세.발판칸.get((x, y + 1)) is None:
        return "지지면이 없다"
    return ""


