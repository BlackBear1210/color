# 배경 슬롯 — **구역 정보 그대로** 배경을 조립한다 (작업지시 §7)
# ----------------------------------------------------------------------------
# ▣ 지키는 규칙
#   · 완성된 방 그림을 상하로 복제하지 않는다. 반복하는 것은 **중간 벽**뿐이고
#     바닥 마감·천장 마감은 실제 경계에 **한 번만** 놓는다.
#   · 소품(책장·커튼)은 구역의 **바닥 앵커**에 붙는다. 물리 발판과 맞물리는 것은
#     시차 이동량 1.0(월드 고정)으로 둬야 한다 — 멀리 흐르는 그림에 콜리전을 붙이지 않는다.
#   · 층마다 이동비율이 다르므로 카메라가 끝까지 가도 그림 밖이 안 드러나는
#     **커버리지**를 층별로 따로 잰다. 1 차 추정 = V + |s|·D + 2M.
# ============================================================================
층_이동비율 = {"L1_먼바탕": 0.15, "L2_먼건축": 0.35, "L3_중경소품": 0.70, "L4_전경": 1.25}
베이_폭칸 = 8          # 첫 베이의 월드 폭 제안값 8 칸 = 768 px (작업지시 §7)
여유_M = 192.0
화면 = (1920.0, 1080.0)


def 배경_슬롯(방) -> list:
    칸 = 방.설정.칸크기
    원점 = (방.설정.원점_x, 방.설정.원점_y)
    슬롯 = []

    def 넣기(구역id, 층, x0칸, x1칸, y0행, y1행, 변형, 접합계열, 월드고정=False):
        슬롯.append({
            "구역": 구역id, "층": 층, "이동비율": 층_이동비율[층],
            "월드고정": 월드고정,
            "사각": [원점[0] + x0칸 * 칸, 원점[1] + y0행 * 칸,
                   (x1칸 - x0칸) * 칸, (y1행 - y0행) * 칸],
            "앵커": [원점[0] + x0칸 * 칸, 원점[1] + y0행 * 칸],
            "변형": 변형, "접합계열": 접합계열,
        })

    # L1 먼 바탕 — 방 전체 + 여유. 양축 반복 가능(초점 없는 어둠)
    넣기("방전체", "L1_먼바탕", 방.L - 2, 방.R + 2, 방.T - 2, 방.B + 2,
       "어둠_A", "집_바탕_XY")

    # L2 먼 건축 — 구역마다 **벽 베이**. 반복은 X 축만. 상단/하단 마감은 따로 한 번.
    for z in 방.구역들:
        x0, x1 = 방.rx(z["x0"]), 방.rx(z["x1"])
        위 = z["지지행"] - 방.설정.단높이          # 그 구역의 천장 = 한 층계 위
        넣기(z["id"], "L2_먼건축", x0, x1, max(방.T, 위), z["지지행"],
           "벽베이_%s" % z["컨셉"], "집_벽베이_v1")
    넣기("바닥", "L2_먼건축", 방.L, 방.R, 방.B, 방.B + 1, "바닥마감", "집_마감_한번")
    넣기("천장", "L2_먼건축", 방.L, 방.R, 방.T - 1, 방.T, "천장마감", "집_마감_한번")

    # L3 중경 소품 — 구역 바닥 앵커에 붙는 가구. 발판과 같은 자리에 오는 것은 월드 고정.
    for z in 방.구역들:
        x0, x1 = 방.rx(z["x0"]), 방.rx(z["x1"])
        넣기(z["id"], "L3_중경소품", x0, min(x1, x0 + 베이_폭칸), z["지지행"] - 3, z["지지행"],
           "소품_%s" % z["컨셉"], "집_소품_v1", 월드고정=True)

    # L4 전경 — 벽 쪽 기둥/문틀. 시야를 다 막지 않게 좁게.
    넣기("좌벽", "L4_전경", 방.L - 1, 방.L + 1, 방.T, 방.B, "기둥_A", "집_전경_v1")
    넣기("우벽", "L4_전경", 방.R - 1, 방.R + 1, 방.T, 방.B, "기둥_A", "집_전경_v1")
    return 슬롯


def 커버리지(방) -> dict:
    """층별로 필요한 그림 범위. 카메라가 방 끝까지 가도 그림 밖이 드러나지 않을 조건."""
    칸 = 방.설정.칸크기
    월드 = (방.W * 칸, 방.H * 칸)
    D = (max(0.0, 월드[0] - 화면[0]), max(0.0, 월드[1] - 화면[1]))   # 카메라 이동 범위
    out = {"월드": 월드, "화면": 화면, "카메라이동": D, "여유": 여유_M, "층": {}}
    for 층, s in 층_이동비율.items():
        out["층"][층] = {
            "이동비율": s,
            "필요폭": 화면[0] + abs(s) * D[0] + 2 * 여유_M,
            "필요높이": 화면[1] + abs(s) * D[1] + 2 * 여유_M,
        }
    return out


