# 전체 검증 — 완료 조건(작업지시 §9)을 항목별로 채점한다
# ============================================================================
def 검증(방, 출구소켓: dict) -> dict:
    보고 = {"항목": [], "실패": []}

    def 항목(이름, 통과, 설명=""):
        보고["항목"].append({"이름": 이름, "통과": bool(통과), "설명": 설명})
        if not 통과:
            보고["실패"].append("%s — %s" % (이름, 설명))
        return 통과

    입구 = next(s for s in 방.소켓들 if s["역할"] == "입구")
    시작 = tuple(입구["칸"])
    출구 = tuple(출구소켓["칸"])

    전 = 세계(방)
    거리 = 이동비용(전, 시작)
    도달 = set(거리)

    # ① 출구 도달
    항목("출구 도달", 출구 in 도달, "비용 %s" % 거리.get(출구, "도달 불가"))

    # ② 계획된 탐색 지점 전부 도달
    못간 = [t["이름"] for t in 방.탐색지점 if tuple(t["칸"]) not in 도달]
    항목("탐색 지점 도달", not 못간, "못 간 곳: %s" % (", ".join(못간) if 못간 else "없음"))

    # ③ 높이가 다른 구역 3 개 이상 (도달 가능한 것만 센다)
    높이들 = set()
    for z in 방.구역들:
        서는 = z["서는행"]
        if any((x, 서는) in 도달 for x in range(방.rx(z["x0"]), 방.rx(z["x1"]))):
            높이들.add(z["높이단"])
    항목("높이 다른 구역 3 개 이상", len(높이들) >= 3, "도달한 높이단 %s" % sorted(높이들))

    # ④ 오른쪽(또는 왼쪽) 보행만으로 끝나지 않는다 — 출구가 바닥 높이가 아니어야 한다
    #    + 주 경로가 서로 다른 높이 구역을 지난다
    항목("출구가 다른 높이 구역", 출구소켓["높이단"] > 0 or len(높이들) >= 3,
       "출구 높이단 %d" % 출구소켓["높이단"])

    # ⑤ 분기 — 한 칸에서 **서로 다른 구역**으로 갈라지는 자리
    분기수 = 갈림길_세기(방, 전, 도달)
    항목("의미 있는 분기 2 개 이상", 분기수 >= 2, "분기 %d 개" % 분기수)

    # ⑥ 복귀 고리 — 위 구역에서 내려와 다시 올라올 수 있다
    돌아옴 = 되돌아올_수_있나(전, 거리, 시작)
    갇힘 = [p for p in 도달 if p not in 돌아옴]
    항목("되돌아오기(갇히는 칸 0)", not 갇힘,
       "갇히는 칸 %d 개 %s" % (len(갇힘), sorted(갇힘)[:4]))
    고리 = 고리_찾기(방, 전, 도달, 시작)
    항목("복귀 고리 1 개 이상", 고리 >= 1, "고리 %d 개" % 고리)

    # ⑦ 관문 강제성 — 행동을 빼고 다시 검사한다
    무점프 = 세계(방, 점프=False)
    무칠 = 세계(방, 칠하기=False)
