# ── 카드 2 · 점프 / 점프대 이펙트 ─────────────────────────────────────────────
def 프레임_띠(rgba, 칸들, 기준점함수, 배율, 상대, 메모):
    """칸(사각) 마다 그림을 떼어 '기준점'(발 자리)이 모든 칸에서 같은 자리에 오도록 가로 띠 한 장으로 붙인다.
    GPT 시트는 칸마다 시작점이 조금씩 어긋난다(Codex 작업기록 카드 2) → 칸 격자를 믿지 않고 그림에서 기준점을 다시 잰다.
    결과: 칸 크기 (w, h) · 기준점 (ax, ay) 가 모든 프레임 공통 → 게임은 region 만 바꿔 재생한다(떨림 없음)."""
    조각들 = []
    for (x0, y0, x1, y1) in 칸들:
        칸 = rgba[y0:y1, x0:x1]
        m = 칸[..., 3] > 20
        if not m.any():
            조각들.append(None)
            continue
        ys, xs = np.where(m)
        bx0, by0, bx1, by1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
        ax, ay = 기준점함수(칸, m, (bx0, by0, bx1, by1))
        조각들.append((칸[by0:by1, bx0:bx1], ax - bx0, ay - by0))
    # 공통 칸: 기준점 왼쪽/오른쪽/위/아래로 가장 먼 거리
    좌 = max(c[1] for c in 조각들 if c)
    우 = max(c[0].shape[1] - c[1] for c in 조각들 if c)
    위 = max(c[2] for c in 조각들 if c)
    아래 = max(c[0].shape[0] - c[2] for c in 조각들 if c)
    반폭 = int(np.ceil(max(좌, 우))) + 2
    w, h = 반폭 * 2, int(np.ceil(위 + 아래)) + 4
    ay_칸 = int(np.ceil(위)) + 2
    띠 = np.zeros((h, w * len(조각들), 4), np.float32)
    for i, c in enumerate(조각들):
        if not c:
            continue
        그림, ax, ay = c
        ox = int(round(i * w + 반폭 - ax))
        oy = int(round(ay_칸 - ay))
        hh, ww = 그림.shape[:2]
        띠[oy:oy + hh, ox:ox + ww] = 그림
    # 저장은 게임 크기의 2배(표시 때 0.5 배) — 0.5 배로 그리면 밉맵 없이도 계단이 안 진다
    # 칸 폭은 정수 px 로 맞춘다(소수 칸이면 region 이 프레임마다 반 px 씩 밀려 떨린다) — 가로 배율이 0.5% 안쪽으로 달라질 뿐
    칸w = max(2, round(w * 배율))
    작은 = 크기바꿈(띠, 너비=칸w * len(조각들), 높이=max(2, round(h * 배율)))
    저장(작은, 상대, 메모)
    정보 = {"프레임": len(조각들), "칸": [칸w, 작은.shape[0]],
          "기준점": [칸w / 2.0, round(ay_칸 * 작은.shape[0] / h, 2)]}
    검사[상대 + "#정보"] = 정보
    return 정보


def 붓결_디테일(rgba, 반전=False):
    """이펙트는 엔진 셰이더가 색을 입힌다(흰 몸 = 흰 물감 184 · 검정 몸 = 잉크 + 밝은 테).
    그래서 PNG 의 RGB 는 '물감 결(디테일)' 만 담는다 — 밝을수록 물감이 두껍다. 알파 = 모양.
    반전 = 검정 잉크 원화(점프대_튕김)일 때: 어두운 곳이 물감이 두꺼운 곳."""
    l = rgba[..., 0] * 0.299 + rgba[..., 1] * 0.587 + rgba[..., 2] * 0.114
    if 반전:
        l = 255.0 - l
    보임 = rgba[..., 3] > 128
    if 보임.any():
        lo, hi = np.percentile(l[보임], 5), np.percentile(l[보임], 98)
        l = (l - lo) / max(1.0, hi - lo) * 0.45 + 0.55       # 0.55~1.0 — 결만 살짝, 덩어리는 고르게
    l = np.clip(l, 0, 1) * 255.0
    return np.dstack([l, l, l, rgba[..., 3]])


