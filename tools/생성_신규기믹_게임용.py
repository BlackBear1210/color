# ── 공통 처리 ─────────────────────────────────────────────────────────────────
def 크로마키(rgb):
    """초록(#00FF00 근처) 배경 → 알파. 원본 배경은 (16~18, 240, 13~17) 이라 단일 RGB 로는 안 지워진다
    (Codex 작업기록) → '초록이 빨강·파랑보다 얼마나 센가' 로 마스크를 만든다. 경계는 부드럽게, 초록 번짐은 뺀다."""
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    초록도 = g - np.maximum(r, b)
    알파 = np.clip((150.0 - 초록도) / (150.0 - 40.0), 0.0, 1.0) * 255.0
    g2 = np.minimum(g, np.maximum(r, b))             # 가장자리 초록 번짐 제거(despill)
    out = np.dstack([r, g2, b, 알파])
    return out


def 흑백(rgba, 목표평균=None, 감마=1.0):
    """R=G=B 로 만든다(검수 기준 §5). 명도는 원본 질감을 살리고 평균만 목표로 옮긴다(곱셈 — 대비 유지)."""
    l = rgba[..., 0] * 0.299 + rgba[..., 1] * 0.587 + rgba[..., 2] * 0.114
    if 감마 != 1.0:
        l = 255.0 * np.power(np.clip(l / 255.0, 0, 1), 감마)
    if 목표평균 is not None:
        보임 = rgba[..., 3] > 128
        if 보임.any():
            l = l * (목표평균 / max(1.0, float(l[보임].mean())))
    l = np.clip(l, 0, 255)
    return np.dstack([l, l, l, rgba[..., 3]])


def 알파범위(rgba, 문턱=24):
    m = rgba[..., 3] > 문턱
    ys, xs = np.where(m)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


def 자르기(rgba, x0, y0, x1, y1, 여백=4):
    h, w = rgba.shape[:2]
    x0, y0 = max(0, x0 - 여백), max(0, y0 - 여백)
    x1, y1 = min(w, x1 + 여백), min(h, y1 + 여백)
    return rgba[y0:y1, x0:x1].copy()


def 크기바꿈(rgba, 너비=None, 높이=None):
    """프리멀티플라이 알파로 줄인다 — 그냥 줄이면 투명 가장자리의 어두운 RGB 가 번져 테두리가 검게 뜬다."""
    h, w = rgba.shape[:2]
    if 너비 and not 높이:
        높이 = max(1, round(h * 너비 / w))
    if 높이 and not 너비:
        너비 = max(1, round(w * 높이 / h))
    a = rgba[..., 3:4] / 255.0
    pm = np.dstack([rgba[..., :3] * a, rgba[..., 3:4]])
    채널 = [np.array(Image.fromarray(pm[..., i].astype(np.float32), "F").resize((너비, 높이), Image.LANCZOS))
           for i in range(4)]
    out = np.dstack(채널)
    a2 = np.clip(out[..., 3:4], 0, 255) / 255.0
    rgb = np.where(a2 > 1e-3, out[..., :3] / np.maximum(a2, 1e-3), 0)
    return np.dstack([rgb, np.clip(out[..., 3], 0, 255)])


def 가로구간(마스크, 최소간격=6):
    """열마다 그림이 있나 → 연속 구간 목록. 시트의 부품을 열 단위로 찾는다."""
    cols = np.where(마스크.any(0))[0]
    if len(cols) == 0:
        return []
    구간, s, p = [], cols[0], cols[0]
    for x in cols[1:]:
        if x > p + 최소간격:
            구간.append((int(s), int(p) + 1))
            s = x
        p = x
    구간.append((int(s), int(p) + 1))
    return 구간


def 세로구간(마스크, 최소간격=6):
    return 가로구간(마스크.T, 최소간격)


