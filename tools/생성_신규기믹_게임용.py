def _띠_메우기(그림, 열들, 대상줄, 원본줄):
    """대상줄(y0, y1) 을 원본줄(s0, s1) 의 줄들을 위에서부터 되풀이해 채운다(열 범위만).
    문짝 판자·쇠창살은 세로로 이어지는 무늬라, 사슬이 없는 줄을 반복해 붙이면 사슬 뒤가 자연스럽게 메워진다."""
    (y0, y1), (s0, s1) = 대상줄, 원본줄
    for x0, x1 in 열들:
        for k, y in enumerate(range(y0, y1)):
            그림[y, x0:x1] = 그림[s0 + k % (s1 - s0), x0:x1]


