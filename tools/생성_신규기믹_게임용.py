def _가장큰덩어리(조, 문턱=40, 번짐=10):
    """칸 안에서 가장 큰 그림 덩어리와 그 둘레(번짐 px)만 남긴다 — 이웃 칸의 잔실·먼지 제거."""
    from scipy import ndimage
    lab, n = ndimage.label(조[..., 3] > 문턱)
    if n > 1:
        큰 = np.argmax(ndimage.sum(np.ones_like(lab), lab, range(1, n + 1))) + 1
        곁 = ndimage.binary_dilation(lab == 큰, iterations=번짐)
        조[..., 3] = np.where(곁, 조[..., 3], 0)
    return 조


